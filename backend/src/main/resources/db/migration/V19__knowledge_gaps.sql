-- Knowledge gaps (12d): questions the knowledge base could not answer, clustered by meaning; reviewers turn a gap
-- into a new article (drafted by the model) or dismiss it.
create table knowledge_gap (
    id            bigint generated by default as identity primary key,
    title         varchar(200) not null,
    status        varchar(16)  not null check (status in ('OPEN', 'DRAFTED', 'PUBLISHED', 'DISMISSED')),
    draft_title   varchar(200),
    draft_content text,
    draft_tags    varchar(300),
    drafted_by    varchar(150),
    article_id    bigint references knowledge_article (id) on delete set null,
    detected_at   timestamp(6) with time zone not null,
    updated_at    timestamp(6) with time zone not null,
    decided_by    varchar(64),
    decided_at    timestamp(6) with time zone
);
create index idx_knowledge_gap_status on knowledge_gap (status);

-- The questions of a gap; deleting a conversation (privacy, retention) deletes its questions here too.
create table knowledge_gap_question (
    id       bigint generated by default as identity primary key,
    gap_id   bigint       not null references knowledge_gap (id) on delete cascade,
    run_id   varchar(255) not null unique references agent_run (id) on delete cascade,
    question text         not null,
    reason   varchar(20)  not null,
    asked_at timestamp(6) with time zone not null
);
create index idx_knowledge_gap_question_gap on knowledge_gap_question (gap_id);
