-- Uploaded documents (12b). Each document is split into chunks stored as knowledge_article rows, so hybrid search,
-- citations and the MCP tools work on them unchanged.
create table knowledge_document (
    id           bigint generated by default as identity primary key,
    title        varchar(200) not null,
    file_name    varchar(255) not null,
    format       varchar(20)  not null,
    size_bytes   bigint       not null,
    status       varchar(20)  not null,
    chunks       integer      not null,
    error        text,
    uploaded_by  varchar(64)  not null,
    uploaded_at  timestamp(6) with time zone not null,
    indexed_at   timestamp(6) with time zone
);

-- The original file, kept apart so that listing documents never loads the bytes; needed to re-index.
create table knowledge_document_file (
    document_id bigint primary key references knowledge_document (id) on delete cascade,
    content     bytea  not null
);

alter table knowledge_article add column document_id bigint references knowledge_document (id) on delete cascade;
create index idx_knowledge_article_document on knowledge_article (document_id);
