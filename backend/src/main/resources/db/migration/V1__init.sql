-- Episodic memory: one row per agent run, plus its trace.
create table agent_run (
    id                varchar(255) primary key,
    session_id        varchar(64)  not null,
    user_id           varchar(64)  not null,
    user_input        text         not null,
    status            varchar(32)  not null,
    final_answer      text,
    iterations        integer      not null,
    tool_calls        integer      not null,
    tool_errors       integer      not null,
    prompt_tokens     bigint       not null,
    completion_tokens bigint       not null,
    active_millis     bigint       not null,
    created_at        timestamp(6) with time zone not null,
    completed_at      timestamp(6) with time zone,
    version           bigint       not null
);
create index idx_agent_run_session on agent_run (session_id);

create table agent_step (
    id              bigint generated by default as identity primary key,
    run_id          varchar(36)  not null,
    type            varchar(32)  not null,
    name            varchar(100),
    content         text,
    error           boolean      not null,
    duration_millis bigint       not null,
    created_at      timestamp(6) with time zone not null
);
create index idx_agent_step_run on agent_step (run_id);

-- Knowledge base (source of truth; embeddings live in vector_store, managed by Spring AI).
create table knowledge_article (
    id      bigint generated by default as identity primary key,
    title   varchar(200) not null,
    content text         not null,
    tags    varchar(300)
);

create table ticket (
    id           bigint generated by default as identity primary key,
    title        varchar(200) not null,
    description  text         not null,
    priority     varchar(16)  not null,
    status       varchar(16)  not null,
    requested_by varchar(64)  not null,
    created_at   timestamp(6) with time zone not null
);

-- Long-term (semantic) memory per user.
create table memory_fact (
    id         bigint generated by default as identity primary key,
    user_id    varchar(64)  not null,
    content    varchar(500) not null,
    created_at timestamp(6) with time zone not null
);
create index idx_memory_fact_user on memory_fact (user_id);
