-- Runs started by the evaluation runner are kept apart from real conversations (dashboard metrics, reviewers' queue).
alter table agent_run add column source varchar(20) not null default 'CHAT';

-- One evaluation = the scenario catalogue run against one model.
create table evaluation (
    id                   varchar(36)  primary key,
    model                varchar(100) not null,
    status               varchar(20)  not null,
    scenario_count       integer      not null,
    completed            integer      not null,
    passed               integer      not null,
    started_by           varchar(64)  not null,
    started_at           timestamp(6) with time zone not null,
    finished_at          timestamp(6) with time zone,
    error                text,
    version              bigint       not null
);

create table evaluation_result (
    id                bigint generated by default as identity primary key,
    evaluation_id     varchar(36)  not null references evaluation (id) on delete cascade,
    scenario_id       varchar(64)  not null,
    category          varchar(32)  not null,
    question          text         not null,
    passed            boolean      not null,
    expected_outcome  varchar(20)  not null,
    outcome           varchar(20)  not null,
    tools_used        varchar(500) not null,
    failures          text         not null,
    answer            text,
    run_id            varchar(36),
    latency_millis    bigint       not null,
    iterations        integer      not null,
    tokens            bigint       not null,
    created_at        timestamp(6) with time zone not null
);
create index idx_evaluation_result_evaluation on evaluation_result (evaluation_id);
