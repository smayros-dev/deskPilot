-- Audit trail of decisions and administrative changes (12o): approvals, settings, documents, evaluations, data deletions.
create table audit_event (
    id          bigint generated by default as identity primary key,
    at          timestamp(6) with time zone not null,
    actor       varchar(64)  not null,
    action      varchar(40)  not null,
    target_type varchar(40),
    target_id   varchar(100),
    details     text
);
create index idx_audit_event_at on audit_event (at desc);
create index idx_audit_event_action on audit_event (action);
create index idx_audit_event_actor on audit_event (actor);
